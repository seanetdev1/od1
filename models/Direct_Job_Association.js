/* THE COMPANY CODE IS NOT ALWAYS THREE LETTERS.
 *
 * This demanded exactly three - [A-Z]{3} - which is true of SNS, ACS and CLS
 * and of nothing else. CargoLinkers' code is CL, so every line of a Direct Job E/R on
 * that install was refused at save with a message naming a format it could
 * never produce: "must follow format SNS-DE-101/26", on a leased customer's
 * screen, quoting our own company code.
 *
 * The tail was wrong too. Document numbers are configurable since 1.2.6 and
 * can read year-first - CL-DE-27/1 - where \d{2} at the end demanded a
 * two-digit sequence. An install that chose that format would have had every
 * entry rejected.
 *
 * So: two to six characters for the company, two to six for the document code,
 * and digits either side of the slash. Loose enough for every install's own
 * numbering, tight enough that free text is still refused - which is all this
 * validator was ever for, since the number is GENERATED by the server (see
 * directJobEntryNo in routes/voucher) and never typed by anyone.
 *
 * THE JOB NUMBER'S DOCUMENT CODE IS OPTIONAL. A clearing job migrated from the
 * legacy system keeps its legacy number - TP-2640/27, no document code - and
 * all 24,159 of CargoLinkers' did, so a line against ANY migrated clearing job
 * was refused at save. Job_No is copied from the job the line is attached to;
 * it is never typed either.
 *
 * Nor is the company code: Config > Document Numbers can leave it off (SEJ-101/26),
 * and codes can be up to eight characters with hyphenated groups. Any
 * upper-case letter/digit groups joined by hyphens, then number/year.
 */
module.exports = (sequelize, DataTypes) => {
  const Direct_Job_Association = sequelize.define(
    "Direct_Job_Association",
    {
      Job_No: {
        type: DataTypes.STRING,
        allowNull: false,
        validate: {
          notEmpty: {
            msg: "Job number is required"
          },
          is: {
            args: /^[A-Z0-9]+(-[A-Z0-9]+)*-\d+\/\d+$/,
            msg: "Job number must look like COMPANY-SE-101/26 (or a migrated TP-101/26) - "
              + "the company code, the document code, then the number and the fiscal year"
          }
        }
      },
      File_No: {
        type: DataTypes.STRING
      },
      Charge_Name: {
        type: DataTypes.STRING,
        allowNull: false
      },

      Basis: {
        type: DataTypes.STRING,
      },

      Rate_Group: {
        type: DataTypes.STRING,
      },

      Size_Type: {
        type: DataTypes.STRING
      },

      Quantity: {
        type: DataTypes.INTEGER,
        allowNull: false
      },

      Currency: {
        type: DataTypes.ENUM(
          "USD",
          "EUR",
          "GBP",
          "AED",
          "OMR",
          "PKR",
          "BDT",
          "CHF"
        ),
        allowNull: false
      },

      Ex_Rate: {
        type: DataTypes.DECIMAL(18, 6),
        allowNull: false
      },

      Amount: {
        type: DataTypes.DECIMAL(18, 6),
        allowNull: false
      },

      Discount: {
        type: DataTypes.DECIMAL(18, 6)
      },

      Tax_Apply: {
        type: DataTypes.BOOLEAN,
        allowNull: false
      },

      Tax_Amount: {
        type: DataTypes.DECIMAL(18, 6)
      },

      VAT_Catagory: {
        type: DataTypes.STRING
      },

      Description: {
        type: DataTypes.STRING
      },

      /* ------------------- which job this line is against -------------------
       * ONE ROW, THREE POSSIBLE OWNERS, and exactly one of them set - the same
       * shape Charge_Heads uses to hang one charge off a freight job, an
       * aviation consignment or a customs job.
       *
       * Job_Id was the ONLY one of these, NOT NULL, with a foreign key to
       * SE_Jobs. That made Direct Job E/R a freight-only screen: under aviation
       * and customs the SE_Jobs table is empty and the jobs live in
       * Aviation_Jobs and Customs_Jobs, so there was no id the column could
       * legally hold and no job an entry could be attached to.
       *
       * A SEPARATE COLUMN PER KIND rather than one id and a 'which table'
       * discriminator: a discriminator is a foreign key the database cannot
       * enforce, and this table is accounting. Each of the three keeps its own
       * FK and its own null.
       *
       * WHICH ONE IS FILLED IS DECIDED BY THE INSTALL'S OPERATION MODE, never
       * by the request - see functions/directJobJobSource, which is the single
       * place that maps a mode to its column, its model and the picker's
       * headings.
       *
       * Job_Id IS NOW NULLABLE. Existing rows all have it and all belong to
       * freight jobs, which is correct and needs no backfill: only a freight
       * install could ever have written one.
       * ------------------------------------------------------------------ */
      Job_Id: {
        type: DataTypes.INTEGER,
        allowNull: true
      },

      AviationJobId: {
        type: DataTypes.INTEGER,
        allowNull: true
      },

      CustomsJobId: {
        type: DataTypes.INTEGER,
        allowNull: true
      },

      Voucher_Id: {
        type: DataTypes.INTEGER,
        allowNull: false
      },

      Direct_Job_Id: {
        type: DataTypes.INTEGER,
        allowNull: false
      },

    },
    {
      tableName: "Direct_Job_Association"
    }
  );

  /* =========================
     Associations
     ========================= */
  Direct_Job_Association.associate = (models) => {
    // One per job kind, each optional. The read routes join whichever the
    // install's mode names - see functions/directJobJobSource.
    Direct_Job_Association.belongsTo(models.SE_Job, {
      foreignKey: "Job_Id",
      as: "Job"
    });

    Direct_Job_Association.belongsTo(models.Aviation_Job, {
      foreignKey: "AviationJobId",
      as: "AviationJob"
    });

    Direct_Job_Association.belongsTo(models.Customs_Job, {
      foreignKey: "CustomsJobId",
      as: "CustomsJob"
    });

    Direct_Job_Association.belongsTo(models.Vouchers, {
      foreignKey: "Voucher_Id",
      as: "Voucher"
    });

    Direct_Job_Association.belongsTo(models.Direct_Job, {
      foreignKey: "Direct_Job_Id",
      as: "DirectJob"
    });
  };

  return Direct_Job_Association;
};
