/* THE COMPANY CODE IS NOT ALWAYS THREE LETTERS.
 *
 * This demanded exactly three - [A-Z]{3} - which is true of SNS, ACS and CLS
 * and of nothing else. CargoLinkers' code is CL, so every Direct Job E/R on
 * that install was refused at save with a message naming a format it could
 * never produce: "must follow format SNS-DE-101/26", on a leased customer's
 * screen, quoting our own company code.
 *
 * The tail was wrong too. Document numbers are configurable since 1.2.6 and
 * can read year-first - CL-DE-27/1 - where \d{2} at the end demanded a
 * two-digit sequence. An install that chose that format would have had every
 * entry rejected.
 *
 * And since Config > Document Numbers the company prefix is optional (DE-101/26)
 * and codes are up to eight characters, hyphenated groups allowed.
 *
 * So: upper-case letter/digit groups joined by hyphens, then digits either side
 * of the slash. Loose enough for every layout the settings can produce, tight
 * enough that free text is still refused - which is all this validator was ever
 * for, since the number is GENERATED by the server (see directJobEntryNo in
 * routes/voucher) and never typed by anyone.
 */
module.exports = (sequelize, DataTypes) => {
  const Direct_Job = sequelize.define(
    "Direct_Job",
    {
      Entry_No: {
        type: DataTypes.STRING,
        allowNull: false,
        validate: {
          notEmpty: {
            msg: "Entry number is required"
          },
          is: {
            args: /^[A-Z0-9]+(-[A-Z0-9]+)*-\d+\/\d+$/,
            msg: "Entry number must look like COMPANY-DE-101/26 or DE-101/26 - the document "
              + "code (with the company code in front, if set), then the number and the fiscal year"
          }
        }
      },

      Type: {
        type: DataTypes.ENUM("expense", "revenue"),
        allowNull: false
      },

      Reference_No: {
        type: DataTypes.STRING
      },

      Operation: {
        type: DataTypes.ENUM("logistics", "other"),
        allowNull: false
      },

      Job_Type: {
        type: DataTypes.ENUM("single", "multiple"),
        allowNull: false
      },

      /* 'adjustment' is for Tran_Mode Adjust - an entry settled against a staff
       * IOU or advance account by journal, which is neither a bank instrument
       * nor cash. The legacy system leaves the sub-type blank on those (886 of
       * CargoLinkers' 1,741 entries), and this column is required.
       *
       * Adding a value to an existing Postgres enum is not something the boot
       * sync does - see cl-deploy/direct-job-adjustment-subtype.sql. */
      SubType: {
        type: DataTypes.ENUM(
          "wire transfer",
          "online transfer",
          "cash",
          "cheque",
          "credit card",
          "po",
          "tt",
          "adjustment"
        ),
        allowNull: false
      },

      Cheque_No: {
        type: DataTypes.STRING
      },

      Cheque_Date: {
        type: DataTypes.DATE
      },

      Currency: {
        type: DataTypes.ENUM(
          "USD",
          "EUR",
          "GBP",
          "AED",
          "OMR",
          "PKR",
          "BDT",
          "CHF"
        ),
        allowNull: false
      },

      Ex_Rate: {
        type: DataTypes.FLOAT,
        allowNull: false
      },

      Tran_Mode: {
        type: DataTypes.ENUM("Cash", "Bank", "Adjust"),
        allowNull: false
      },

      Drawn_At: {
        type: DataTypes.STRING
      },

      Account_No: {
        type: DataTypes.INTEGER,
        allowNull: false
      },

      Paid_To: {
        type: DataTypes.INTEGER,
        allowNull: true
      }
    },
    {
      tableName: "Direct_Jobs"
    }
  );

  /* =========================
     Associations
     ========================= */
  Direct_Job.associate = (models) => {
    Direct_Job.belongsTo(models.Child_Account, {
      foreignKey: "Account_No",
      as: "AccountNo"
    });

    Direct_Job.belongsTo(models.Child_Account, {
      foreignKey: "Paid_To",
      as: "PaidTo"
    });

    Direct_Job.hasMany(models.Direct_Job_Association, {
      foreignKey: "Direct_Job_Id",
      as: "Associations"
    });
  };

  return Direct_Job;
};
