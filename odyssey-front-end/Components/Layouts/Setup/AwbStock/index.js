import React, { useCallback, useEffect, useRef, useState } from 'react';
import { Row, Col, Table } from 'react-bootstrap';
import { Input, Select, Radio, Pagination, Tag, Spin, Checkbox, Tooltip } from 'antd';
import { DeleteOutlined, RollbackOutlined, StopOutlined, UndoOutlined } from '@ant-design/icons';
import Cookies from 'js-cookie';
import PopConfirm from 'Components/Shared/PopConfirm';
import openNotification from 'Components/Shared/Notification';
import { getAwbList, deleteAwb, unassignAwbs, unvoidAwbs } from 'apis/awbStock';
import { UserAddOutlined } from '@ant-design/icons';
import { usePageActions } from 'Components/Shared/PageActions';
import { getAviationValues, getCarriers } from 'apis/aviationJobs';
import RegisterModal from './RegisterModal';
import AssignModal from './AssignModal';
import VoidModal from './VoidModal';

// Setup > AWB Stock. Aviation only.
//
// The register of air waybill numbers the office holds. Two jobs, in the order
// they happen:
//
//   REGISTER   numbers against the carrier that issued them. An AWB is a
//              3-digit carrier prefix, a 7-digit serial and a check digit that
//              is the serial modulo 7 - so a block is generated by counting
//              the serial and recalculating the digit, never by counting the
//              last digit up. See functions/awbNumber.js.
//
//   ASSIGN     them to a master agent. One number, one agent: that is a single
//              column on the table, so it is not a rule something has to
//              remember to check. UNASSIGN takes one back into office stock,
//              which is what happens when an agent returns a block they never
//              used - offered per row and on the ticked selection, because
//              both a single returned number and a whole block come back.
//
//   VOID       a number whose document is spoiled - torn, misprinted, lost.
//              It STAYS on the register, because the airline allocated that
//              serial and will ask what became of it, but nothing can use it
//              any more. Restorable, since a mis-click must not cost a number
//              permanently. See VoidModal and routes aviationJobs/awb.js.
//
// No company selector. AWB stock is held by the office, not by one of its
// companies - which company used a number is answered by the flight it is on.
const PAGE_SIZE = 20;

// The states a number moves through, as the filters someone actually wants.
// 'available' is the working set: registered, not given out, not yet flown.
const STATUSES = [
  ['all',        'All'],
  ['available',  'In stock'],
  ['assigned',   'Assigned'],
  ['used',       'Used'],
  ['voided',     'Voided'],
];

const AwbStock = () => {
  const employeeId = Cookies.get('loginId');

  const [carriers, setCarriers] = useState([]);
  const [masterAgents, setMasterAgents] = useState([]);

  const [rows, setRows] = useState([]);
  const [total, setTotal] = useState(0);
  const [page, setPage] = useState(1);
  const [search, setSearch] = useState('');
  const [carrierId, setCarrierId] = useState(undefined);
  const [masterAgentId, setMasterAgentId] = useState(undefined);
  const [status, setStatus] = useState('all');
  const [loading, setLoading] = useState(true);
  const [selected, setSelected] = useState(new Set());
  const [registerOpen, setRegisterOpen] = useState(false);
  const [assignOpen, setAssignOpen] = useState(false);
  // The rows the void modal is working on. Held as rows rather than ids so it
  // can name the numbers back to the operator before they agree to it - and
  // set from either one row's icon or the whole ticked selection, which is why
  // it is a list even for a single one.
  const [voidRows, setVoidRows] = useState([]);

  // Carriers own the prefixes; master agents are parties tagged 'Master Agent',
  // which /aviationJob/getValues already filters for the consignment grid -
  // reusing it keeps one definition of who a master agent is.
  useEffect(() => {
    (async () => {
      try {
        const [c, v] = await Promise.all([getCarriers(), getAviationValues()]);
        setCarriers(Array.isArray(c?.result) ? c.result : []);
        setMasterAgents(v?.result?.masterAgent || []);
      } catch (e) {
        openNotification('Error', 'Could not load carriers and master agents.', 'red');
      }
    })();
  }, []);

  // Every filter goes back to the server; nothing is narrowed in the browser,
  // so the page stays usable with tens of thousands of numbers registered.
  const load = useCallback(async (opts = {}) => {
    setLoading(true);
    try {
      const res = await getAwbList({
        page: opts.page ?? page,
        limit: PAGE_SIZE,
        search: opts.search ?? search,
        carrierId: opts.carrierId ?? carrierId,
        masterAgentId: opts.masterAgentId ?? masterAgentId,
        status: opts.status ?? status,
      });
      if (res.status !== 'success') {
        openNotification('Error', res.result || 'Could not load the register.', 'red');
        return;
      }
      setRows(res.result.rows);
      setTotal(res.result.count);
    } catch (e) {
      openNotification('Error', e?.response?.data?.result || 'Could not load the register.', 'red');
    } finally {
      setLoading(false);
    }
  }, [page, search, carrierId, masterAgentId, status]);

  // Selection is cleared whenever the visible set changes: a tick that
  // survives a filter change is a number the user can no longer see and is
  // about to assign by accident.
  useEffect(() => {
    setPage(1);
    setSelected(new Set());
    load({ page: 1 });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [carrierId, masterAgentId, status]);

  // Debounced, so typing a number is one request rather than eight.
  const searchTimer = useRef(null);
  const onSearchChange = (value) => {
    setSearch(value);
    clearTimeout(searchTimer.current);
    searchTimer.current = setTimeout(() => {
      setPage(1);
      setSelected(new Set());
      load({ page: 1, search: value });
    }, 400);
  };

  const toggle = (id) => setSelected((s) => {
    const next = new Set(s);
    if (next.has(id)) next.delete(id); else next.add(id);
    return next;
  });

  // Used and voided numbers are never selectable.
  //
  // A used one is on a flight, so neither assigning it elsewhere nor taking it
  // back is a thing that can happen. A VOIDED one is frozen as it was voided -
  // its agent included, because that is who was holding the spoiled document -
  // so assign and unassign both refuse it on the server. Leaving it tickable
  // would only offer bulk actions that come back as errors; Restore, on its
  // own row, is the one thing that can be done to it.
  const selectable = rows.filter((r) => !r.useCount && !r.voidedAt);
  const allSelected = selectable.length > 0 && selectable.every((r) => selected.has(r.id));
  const toggleAll = () => setSelected((s) => {
    const next = new Set(s);
    if (allSelected) selectable.forEach((r) => next.delete(r.id));
    else selectable.forEach((r) => next.add(r.id));
    return next;
  });

  // Takes an explicit list, so the row icon and the selection bar are the same
  // action rather than two that could drift apart. `what` is what to call them
  // in the confirmation: one row says its number, the bar says how many.
  const takeBack = (ids, what) => {
    if (!ids.length) return openNotification('Error', 'Tick the numbers to take back first.', 'red');
    PopConfirm('Confirmation', `Take ${what} back into office stock?`, async () => {
      try {
        const res = await unassignAwbs({ ids, employeeId });
        if (res.status !== 'success') {
          openNotification('Not released', res.result || 'Could not take these back.', 'red');
          return;
        }
        openNotification('Done', `${res.result.released} number(s) returned to stock.`, 'green');
        setSelected(new Set());
        load();
      } catch (e) {
        openNotification('Not released', e?.response?.data?.result || 'Could not take these back.', 'red');
      }
    });
  };

  const restore = (row) => {
    PopConfirm(
      'Confirmation',
      `Restore ${row.formatted}? It becomes usable again, and goes back to ` +
      `${row.masterAgent || 'office stock'}.`,
      async () => {
        try {
          const res = await unvoidAwbs({ ids: [row.id], employeeId });
          if (res.status !== 'success') {
            openNotification('Not restored', res.result || 'Could not restore.', 'red');
            return;
          }
          openNotification('Restored', `${row.formatted} is usable again.`, 'green');
          load();
        } catch (e) {
          openNotification('Not restored', e?.response?.data?.result || 'Could not restore.', 'red');
        }
      }
    );
  };

  const remove = (row) => {
    PopConfirm('Confirmation', `Remove ${row.formatted} from the register?`, async () => {
      try {
        const res = await deleteAwb({ id: row.id, employeeId });
        if (res.status !== 'success') {
          openNotification('Not removed', res.result || 'Could not remove.', 'red');
          return;
        }
        openNotification('Removed', `${row.formatted} is no longer registered.`, 'green');
        load();
      } catch (e) {
        openNotification('Not removed', e?.response?.data?.result || 'Could not remove.', 'red');
      }
    });
  };

  // VOIDED WINS over everything else the row could be called. A voided number
  // may still be sitting with an agent, but "Assigned" would tell the operator
  // it is out there waiting to be used, which is the one thing it is not.
  const stateOf = (row) => {
    if (row.voidedAt) {
      return (
        <Tooltip title={row.voidReason ? `${row.voidReason} — ${(row.voidedAt || '').slice(0, 10)}` : undefined}>
          <Tag color='red'>Voided</Tag>
        </Tooltip>
      );
    }
    if (row.useCount) return <Tag color='blue'>Used</Tag>;
    if (row.masterAgentId) return <Tag color='gold'>Assigned</Tag>;
    return <Tag color='green'>In stock</Tag>;
  };

  /* Register AWB is this page's New: it is how a record gets created here.
     Assign is the screen's own verb and rides in extras, after the five, so
     the standard positions do not shift on this page alone. */
  usePageActions({
    title: 'AWB Stock',
    new: {
      onClick: () => setRegisterOpen(true),
      label: 'Register AWB',
      title: 'Register a new AWB into stock',
    },
    extras: [{
      key: 'assign',
      label: 'Assign',
      Icon: UserAddOutlined,
      onClick: () => setAssignOpen(true),
      title: 'Assign stock to a master agent',
    }],
  }, []);

  return (
    <div className='base-page-layout awb-stock-page'>
      <Row className='align-items-center g-2'>
        <Col md={2}>
          <Select allowClear showSearch style={{ width: '100%' }} placeholder='All carriers'
            value={carrierId} onChange={setCarrierId} optionFilterProp='label'
            options={carriers.map((c) => ({
              value: c.id, label: c.prefix ? `${c.prefix} — ${c.name}` : c.name,
            }))} />
        </Col>
        <Col md={3}>
          <Select allowClear showSearch style={{ width: '100%' }} placeholder='All master agents'
            value={masterAgentId} onChange={setMasterAgentId} optionFilterProp='label'
            options={masterAgents.map((a) => ({ value: a.id, label: a.name }))} />
        </Col>
        <Col md={2}>
          <Radio.Group value={status} onChange={(e) => setStatus(e.target.value)} size='small'>
            {STATUSES.map(([value, label]) => (
              <Radio.Button key={value} value={value}>{label}</Radio.Button>
            ))}
          </Radio.Group>
        </Col>
        <Col md={2}>
          <Input allowClear placeholder='Search AWB number'
            value={search} onChange={(e) => onSearchChange(e.target.value)} />
        </Col>
      </Row>

      {selected.size > 0 && (
        <div className='awb-selbar'>
          <b>{selected.size}</b> selected
          <a onClick={() => setAssignOpen(true)}>Assign to a master agent</a>
          <a onClick={() => takeBack([...selected], `${selected.size} number(s)`)}>
            Unassign — take back into stock
          </a>
          <a className='danger-link'
            onClick={() => setVoidRows(rows.filter((r) => selected.has(r.id)))}>
            Void
          </a>
          <a onClick={() => setSelected(new Set())}>Clear</a>
        </div>
      )}

      <Spin spinning={loading}>
        <div style={{ minHeight: 380 }}>
          <Table className='mt-2' style={{ fontSize: 13 }}>
            <thead>
              <tr>
                <th style={{ width: 34 }}>
                  <Checkbox checked={allSelected} disabled={!selectable.length} onChange={toggleAll} />
                </th>
                <th>AWB number</th>
                <th>Carrier</th>
                <th>Master agent</th>
                <th>State</th>
                <th>On flight</th>
                <th>Remarks</th>
                <th></th>
              </tr>
            </thead>
            <tbody>
              {rows.map((row) => (
                <tr key={row.id}
                  className={`${row.useCount ? 'is-used' : ''} ${row.voidedAt ? 'is-voided' : ''}`}>
                  <td>
                    <Checkbox checked={selected.has(row.id)}
                      disabled={Boolean(row.useCount) || Boolean(row.voidedAt)}
                      title={row.voidedAt
                        ? 'Voided — restore it first'
                        : (row.useCount ? 'On a flight — cannot be reassigned' : undefined)}
                      onChange={() => toggle(row.id)} />
                  </td>
                  <td className='mono fw-7 blue-txt'>{row.formatted}</td>
                  <td>{row.carrier || '—'}</td>
                  <td>{row.masterAgent || <span className='grey-txt'>in stock</span>}</td>
                  <td>{stateOf(row)}</td>
                  <td className='grey-txt'>
                    {/* The same AWB can be on more than one flight - that is a
                        shipment split across aircraft, not a duplicate. */}
                    {row.flights?.length
                      ? row.flights.map((f) => f.jobNo || f.flightNo).join(', ')
                      : '—'}
                  </td>
                  <td className='grey-txt'>
                    {/* On a voided row the reason is what anyone opening this
                        screen is actually looking for, so it takes the column
                        and the ordinary remark follows it. */}
                    {row.voidedAt
                      ? <><b className='danger-txt'>Voided: {row.voidReason || 'no reason given'}</b>
                          {row.remarks ? ` — ${row.remarks}` : ''}</>
                      : (row.remarks || '')}
                  </td>
                  <td className='text-end awb-actions'>
                    {/* A voided row offers only the way back. Assign, unassign
                        and delete all refuse it on the server, so showing them
                        would only be a way to collect an error message. */}
                    {row.voidedAt ? (
                      <Tooltip title='Restore — make this number usable again'>
                        <UndoOutlined className='action-icon' onClick={() => restore(row)} />
                      </Tooltip>
                    ) : !row.useCount && (
                      <>
                        {/* Per row as well as on the selection, because a single
                            number handed back is as common as a whole block. */}
                        {row.masterAgentId && (
                          <Tooltip title={`Unassign — take back from ${row.masterAgent || 'the agent'}`}>
                            <RollbackOutlined className='action-icon'
                              onClick={() => takeBack([row.id], row.formatted)} />
                          </Tooltip>
                        )}
                        <Tooltip title='Void — torn, misprinted or lost'>
                          <StopOutlined className='danger-icon' onClick={() => setVoidRows([row])} />
                        </Tooltip>
                        <Tooltip title='Remove from the register'>
                          <DeleteOutlined className='danger-icon' onClick={() => remove(row)} />
                        </Tooltip>
                      </>
                    )}
                  </td>
                </tr>
              ))}
              {!rows.length && !loading && (
                <tr>
                  <td colSpan={8} className='text-center grey-txt py-5'>
                    {search || carrierId || masterAgentId || status !== 'all'
                      ? 'No AWB numbers match these filters.'
                      : 'No AWB numbers registered yet. Use Register AWB to add the block the airline allocated.'}
                  </td>
                </tr>
              )}
            </tbody>
          </Table>
        </div>
      </Spin>

      <div className='d-flex justify-content-end mt-2'>
        <Pagination current={page} pageSize={PAGE_SIZE} total={total} showSizeChanger={false}
          showTotal={(t) => `${t} number${t === 1 ? '' : 's'}`}
          onChange={(p) => { setPage(p); setSelected(new Set()); load({ page: p }); }} />
      </div>

      <RegisterModal open={registerOpen} onClose={() => setRegisterOpen(false)}
        onSaved={() => load({ page: 1 })} carriers={carriers} employeeId={employeeId} />

      <AssignModal open={assignOpen} onClose={() => setAssignOpen(false)}
        onSaved={() => { setSelected(new Set()); load(); }}
        carriers={carriers} masterAgents={masterAgents}
        selectedIds={[...selected]} employeeId={employeeId} />

      <VoidModal open={voidRows.length > 0} onClose={() => setVoidRows([])}
        onSaved={() => { setSelected(new Set()); load(); }}
        rows={voidRows} employeeId={employeeId} />

      <style jsx global>{`
        .awb-stock-page .mono { font-variant-numeric: tabular-nums; }
        .awb-stock-page tr.is-used td { background: #fafcff; }
        /* A voided row reads as struck off at a glance - the number itself is
           ruled through, which is what a spoiled air waybill looks like on
           paper. */
        .awb-stock-page tr.is-voided td { background: #fffafa; color: #8c8c8c; }
        .awb-stock-page tr.is-voided .mono { text-decoration: line-through; color: #8c8c8c; }
        .awb-stock-page .danger-icon { color: #cf1322; cursor: pointer; }
        .awb-stock-page .danger-txt { color: #cf1322; }
        .awb-stock-page .action-icon { color: #1677ff; cursor: pointer; }
        .awb-stock-page .awb-actions { white-space: nowrap; }
        .awb-stock-page .awb-actions .anticon + .anticon { margin-left: 12px; }
        .awb-stock-page .awb-selbar .danger-link { color: #cf1322; }
        .awb-stock-page .awb-selbar {
          display: flex;
          align-items: center;
          gap: 14px;
          margin-top: 10px;
          padding: 6px 10px;
          font-size: 12px;
          background: #f6f9fc;
          border: 1px solid #e6eef5;
          border-radius: 4px;
        }
        .awb-stock-page .awb-selbar a { cursor: pointer; }
      `}</style>
    </div>
  );
};

export default AwbStock;
